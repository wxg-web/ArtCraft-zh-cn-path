  const ignoredTags = new Set([
    "SCRIPT",
    "STYLE",
    "NOSCRIPT",
    "TEXTAREA",
    "INPUT",
    "CODE",
    "PRE",
  ]);

  function translateValue(value) {
    if (!value) {
      return value;
    }
    const trimmed = value.trim();
    if (!trimmed) {
      return value;
    }

    const exact = normalized.get(trimmed.toLocaleLowerCase());
    if (exact) {
      return value.replace(trimmed, exact);
    }

    for (const [pattern, replacement] of dynamicRules) {
      if (pattern.test(trimmed)) {
        return value.replace(trimmed, trimmed.replace(pattern, replacement));
      }
    }
    return value;
  }

  function shouldSkip(element) {
    return (
      !element ||
      ignoredTags.has(element.tagName) ||
      element.isContentEditable ||
      element.closest("[contenteditable='true']") ||
      element.closest("[data-artcraft-zh-skip]")
    );
  }

  function translateTextNode(node) {
    if (!node.nodeValue || shouldSkip(node.parentElement)) {
      return;
    }
    const next = translateValue(node.nodeValue);
    if (next !== node.nodeValue) {
      node.nodeValue = next;
    }
  }

  const attributeNames = ["aria-label", "placeholder", "title", "alt"];

  function translateAttributes(element) {
    for (const name of attributeNames) {
      const value = element.getAttribute(name);
      if (!value) {
        continue;
      }
      const next = translateValue(value);
      if (next !== value) {
        element.setAttribute(name, next);
      }
    }
  }

  let queued = false;

  function translateTree(root = document.body) {
    if (!root) {
      return;
    }
    if (root.nodeType === Node.TEXT_NODE) {
      translateTextNode(root);
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) {
      return;
    }

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      translateTextNode(node);
    }

    const elements =
      root.nodeType === Node.ELEMENT_NODE
        ? [root, ...root.querySelectorAll("*")]
        : [...root.querySelectorAll("*")];
    for (const element of elements) {
      translateAttributes(element);
    }
  }

  function scheduleTranslate() {
    if (queued) {
      return;
    }
    queued = true;
    queueMicrotask(() => {
      queued = false;
      translateTree(document.body);
    });
  }

  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "characterData") {
        translateTextNode(mutation.target);
      } else if (mutation.type === "attributes") {
        if (mutation.target instanceof Element) {
          translateAttributes(mutation.target);
        }
      } else {
        for (const node of mutation.addedNodes) {
          translateTree(node);
        }
      }
    }
  });

  function start() {
    translateTree(document.body);
    observer.observe(document.documentElement, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: attributeNames,
    });
    scheduleTranslate();
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", start, { once: true });
  } else {
    start();
  }
